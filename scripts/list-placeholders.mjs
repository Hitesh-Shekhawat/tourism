// Writes BUSINESS_INFO_REQUIRED.md: every unfilled {{PLACEHOLDER}} and owner-supplied block, and where it lives.
import fs from "node:fs";
import path from "node:path";

const ROOTS = ["content", "app", "components", "lib"];
const files = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(e.name)) files.push(p);
  }
};
ROOTS.forEach((r) => fs.existsSync(r) && walk(r));

const facts = new Map(); // name -> Set(location)
const local = []; // {{local detail: …}}
for (const f of files) {
  const rel = f.replace(/\\/g, "/");
  fs.readFileSync(f, "utf8")
    .split("\n")
    .forEach((line, i) => {
      if (/^\s*(\*|\/\/|\/\*)/.test(line)) return; // comments
      for (const m of line.matchAll(/\{\{([^}]+)\}\}/g)) {
        const name = m[1].trim();
        if (/^(local detail|on-trip)/i.test(name)) local.push({ text: name, at: `${rel}:${i + 1}` });
        else if (/^[A-Z_]+$/.test(name)) {
          if (!facts.has(name)) facts.set(name, new Set());
          facts.get(name).add(`${rel}:${i + 1}`);
        }
      }
    });
}

const read = (f) => fs.readFileSync(f, "utf8");
const count = (f, re) => (read(f).match(re) || []).length;
const tourFiles = fs.readdirSync("content/tours").filter((f) => !/^(index|types)\.ts$/.test(f));
const drafts = tourFiles.filter((f) => /draft:\s*true/.test(read(`content/tours/${f}`)));
const nullFaqs = count("content/home.ts", /\{ q: .*\ba: null \}/g);
const nullReasons = count("content/home.ts", /proof: null/g);
const nullExp = count("content/experiences.ts", /included: null/g);
const assets = read("content/assets.ts");
const assetTotal = (assets.match(/^\s+\w+: a\(/gm) || []).length;
const assetDone = (assets.match(/\{ src: "\/images\/[^<]/g) || []).length;
const legalNull = count("content/legal.ts", /sections: null/g);
const day = JSON.parse(read("content/day.json"));
const seqs = Object.entries(day.frameSequences);

let md = `# Business information required

Generated by \`npm run placeholders\` on ${new Date().toISOString().slice(0, 10)}. Re-run it after filling things in.

Nothing here may be invented. Until each item is filled, the site shows it as a visible dashed placeholder, and \`npm run build\` **fails** while any rendered page still contains one. (\`ALLOW_PLACEHOLDERS=true npm run build\` allows a preview build.)

## 1 · Business facts (\`content/business.ts\`)

Replace the whole \`"{{…}}"\` string, braces included.

| Placeholder | Used in |
|---|---|
`;
for (const [name, locs] of [...facts].sort()) md += `| \`{{${name}}}\` | ${[...locs].map((l) => `\`${l}\``).join("<br>")} |\n`;

md += `
Also in \`content/business.ts\`, currently empty and therefore hidden:

- \`approvals\`: Ministry of Tourism / RTDC / IATO etc., **only if real**, each with its registration number (and optional logo). Shown in the footer, Our Story and the home "Why travel with us" block.
- \`social\`: real Instagram / Facebook / YouTube URLs only.
- \`openingHoursSchema\`: e.g. \`["Mo-Sa 09:30-19:00"]\` for search engines.
- \`gstin\`: set to \`""\` if not applicable.

## 2 · Environment variables (\`.env.example\`)

- \`NEXT_PUBLIC_SITE_URL\`: the live domain. Canonicals, sitemap and Open Graph use it; the build fails while it is unset.
- \`RESEND_API_KEY\`, \`ENQUIRY_TO_EMAIL\`, \`ENQUIRY_FROM_EMAIL\`: without these the enquiry form **honestly fails** and points guests to WhatsApp and phone.
- \`NEXT_PUBLIC_TURNSTILE_SITE_KEY\`, \`TURNSTILE_SECRET_KEY\`: required in production.
- \`NEXT_PUBLIC_GA_ID\`: optional; no analytics or cookie banner without it.

## 3 · Content the owner must write or confirm

| What | Where | Status |
|---|---|---|
| Tours: the real route, days, inclusions, exclusions, hotel category, price | \`content/tours/*.ts\` | ${drafts.length} of ${tourFiles.length} are sample drafts (\`draft: true\`)${drafts.length ? `: ${drafts.join(", ")}` : ""} |
| FAQ answers | \`content/home.ts\` → \`faqs\` | ${nullFaqs} of 7 unanswered |
| "Why travel with us": the fact behind each claim | \`content/home.ts\` → \`reasons\` | ${nullReasons} without proof |
| Home "Why travel with us": which services you really offer (\`true\`, or \`false\` to hide one) | \`content/homepage.ts\` → \`services\` | ${(read("content/homepage.ts").match(/offered: null }/g) || []).length} of 8 unconfirmed |
| Home guest video stories (real guests, written permission) | \`content/homepage.ts\` → \`travellerStories\` | ${/travellerStories: TravellerStory\[\] = \[\]/.test(read("content/homepage.ts")) ? "none yet (section hidden)" : "supplied"} |
| Home hero footage (optional; the hero photo shows until then) | \`content/homepage.ts\` → \`heroVideo\` | ${/heroVideo: [^=]+= \{\}/.test(read("content/homepage.ts")) ? "none (photo only)" : "supplied"} |
| Experiences: what's included | \`content/experiences.ts\` → \`included\` | ${nullExp} of 6 missing |
| Guest reviews (real, with permission) | \`content/home.ts\` → \`reviews\` | ${(read("content/home.ts").match(/reviews[^=]*= \[\]/) ? "none yet (honest 'coming soon' block shows)" : "supplied")} |
| Privacy, Terms, Cancellation & Refund | \`content/legal.ts\` | ${legalNull} of 3 missing |
| Founder / team story and photos | \`app/our-story/page.tsx\` | placeholder blocks |
| Photos | \`content/assets.ts\` (see ASSET_BRIEF.md) | ${assetDone} of ${assetTotal} photos supplied |
${seqs.map(([n, q]) => `| Frame sequence \`${n}\` (scroll story) | \`public${q.desktop.dir.replace("/desktop", "")}/\`, status in \`content/day.json\` | ${q.status === "ready" ? "ready" : "**owner to supply**: placeholder frames in place, and the production build fails until they are replaced (brief in ASSET_BRIEF.md; convert with \`scripts/video-to-frames.sh\`)"} |`).join("\n")}
| Journal articles (optional) | \`content/journal.ts\` | ${/journal: Article\[\] = \[\]/.test(read("content/journal.ts")) ? "none (section, nav link and routes hidden)" : "published"} |

## 4 · Local details to verify or write (${local.length})

These sit inside otherwise-written copy. Replace each with something true and specific, or delete the sentence.

`;
for (const l of local) md += `- \`${l.at}\`: ${l.text}\n`;

fs.writeFileSync("BUSINESS_INFO_REQUIRED.md", md);
console.log(`BUSINESS_INFO_REQUIRED.md: ${facts.size} business facts, ${local.length} local details, ${drafts.length} draft tours.`);
